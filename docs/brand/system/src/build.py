"""Builds everything in carreta-final from src/. Run from anywhere:
    python3 -I src/build.py
1. carreta.css  = font faces + generated tokens + src/css/*.css
2. tokens.json, migration.json, and the generated tables of SISTEMA.md (TOKENS,
   MIGRATION and ESTADOS markers)
3. every reference page (shop, tools, apps, misc) and index.html
Fonts (src/fonts.py), assets (src/assets.py), lockups (src/logo.py) and PNGs
(src/render.js) are separate steps; see SISTEMA.md §15."""
import os, sys, glob, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokens as T
import common
ROOT = common.ROOT

# one woff2 per weight (src/fonts.py), no unicode-range: the same files next/font/local loads
faces = [
    '@font-face{font-family:"Fira Sans";font-weight:%d;font-display:swap;src:url(fonts/web/fira-sans-%d.woff2) format("woff2")}' % (w, w) for w in (400, 500, 600, 700)
] + [
    '@font-face{font-family:"Epilogue";font-weight:%d;font-display:swap;src:url(fonts/web/epilogue-%d.woff2) format("woff2")}' % (w, w) for w in (600, 700, 800)
]
parts = [open(p).read() for p in sorted(glob.glob(os.path.join(ROOT, 'src', 'css', '*.css')))]
css = ('/* Carreta final. GENERATED by src/build.py from src/tokens.py and src/css/*.css. Do not edit by hand. */\n'
       + '\n'.join(faces) + '\n' + T.css_root() + '\n' + T.css_type() + '\n' + '\n'.join(parts))
open(os.path.join(ROOT, 'carreta.css'), 'w').write(css)
open(os.path.join(ROOT, 'tokens.json'), 'w').write(T.json_tokens())

md = os.path.join(ROOT, 'SISTEMA.md')
if os.path.exists(md):
    s = open(md).read()
    s = re.sub(r'(<!-- TOKENS -->).*?(<!-- /TOKENS -->)', lambda m: m.group(1) + '\n' + T.md_tables() + '\n' + m.group(2), s, flags=re.S)
    import migration as M
    M.write_json()
    s = re.sub(r'(<!-- MIGRATION -->).*?(<!-- /MIGRATION -->)', lambda m: m.group(1) + '\n' + M.md_migration() + '\n' + m.group(2), s, flags=re.S)
    s = re.sub(r'(<!-- ESTADOS -->).*?(<!-- /ESTADOS -->)', lambda m: m.group(1) + '\n' + M.md_states() + '\n' + m.group(2), s, flags=re.S)
    open(md, 'w').write(s)

import shop, tools, apps, misc
shop.home(); shop.lista(); shop.tienda(); shop.producto(); shop.sugerencias(); shop.carrito(); shop.pago(); shop.pedido(); shop.pedidos()
shop.comprobante(); shop.cuenta(); shop.zona(); shop.ingresar(); shop.avisos(); shop.ayuda()
tools.consola(); tools.central_resumen(); tools.central_atencion(); tools.central_catalogo(); tools.central_pedido(); tools.central_feriados()
tools.vende_inicio(); tools.vende_productos(); tools.vende_publicar(); tools.vende_invitaciones(); tools.vende_comprobante()
tools.campo(); tools.ruta_lista(); tools.ruta_parada(); tools.bodega_tareas(); tools.bodega()
import runpy
runpy.run_path(os.path.join(ROOT, 'src', 'apps.py'), run_name='__main__')
misc.sistema(); misc.iconos(); misc.logotipos(); misc.mensajes(); misc.cubrir(); misc.confirmar(); misc.franja_pages(); misc.index()
import json
json.dump(common.PAGES, open(os.path.join(ROOT, 'src', 'pages.json'), 'w'), ensure_ascii=False, indent=0)
